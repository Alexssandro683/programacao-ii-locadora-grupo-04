CREATE TABLE IF NOT EXISTS cliente (
    id_cliente BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cpf VARCHAR(11) NOT NULL UNIQUE,
    CONSTRAINT ck_cliente_cpf_digitos
    CHECK (cpf ~ '^[0-9]{11}$')
    );

CREATE TABLE IF NOT EXISTS veiculo (
    id_veiculo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo VARCHAR(100) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    placa VARCHAR(7) NOT NULL UNIQUE,
    valor_diaria NUMERIC(12, 2) NOT NULL,
    disponivel BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT ck_veiculo_tipo
        CHECK (tipo IN ('CARRO', 'MOTO', 'VAN', 'QUADRICICLO')),
    CONSTRAINT ck_veiculo_valor_diaria_positivo
        CHECK (valor_diaria > 0),
    CONSTRAINT ck_veiculo_placa_formato
        CHECK (placa ~ '^[A-Z0-9]{7}$')
    );

CREATE TABLE IF NOT EXISTS locacao (
    id_locacao BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente BIGINT NOT NULL,
    id_veiculo BIGINT NOT NULL,
    dias_contratados INTEGER NOT NULL,
    valor_total NUMERIC(12, 2) NOT NULL,
    ativa BOOLEAN NOT NULL DEFAULT TRUE,

    CONSTRAINT fk_locacao_cliente
        FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente)
        ON DELETE RESTRICT,

    CONSTRAINT fk_locacao_veiculo
        FOREIGN KEY (id_veiculo)
        REFERENCES veiculo (id_veiculo)
        ON DELETE RESTRICT,

    CONSTRAINT ck_locacao_dias_positivos
        CHECK (dias_contratados > 0),

    CONSTRAINT ck_locacao_valor_total_positivo
        CHECK (valor_total > 0)
    );

CREATE UNIQUE INDEX IF NOT EXISTS uq_locacao_veiculo_ativa
    ON locacao (id_veiculo)
    WHERE ativa = TRUE;
